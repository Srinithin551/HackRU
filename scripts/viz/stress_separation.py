#!/usr/bin/env python
"""How well does the stress score separate calm from stressed periods? Recommends constants.

    python scripts/viz/stress_separation.py checkpoint_phase4

Labels each reading from the mock_vitals --events-out CSV (or, for real Presage data, any
<name>_events.csv with time,key rows), then reports per-reading and per-10-s-window
separation (what Brain's watcher sees), threshold hit/false-alarm rates, and how the
calm noise floor and spike peak move if the HR/BR constants change.
Writes docs/data/stats_<name>.md.
"""
import argparse
import sys
from datetime import timezone

import numpy as np
import pandas as pd
from scipy import stats

import style
from qa_report import label_rows

sys.path.insert(0, str(style.ROOT))
from backend.contracts import Baseline, VitalsReading  # noqa: E402
from backend.data import metrics  # noqa: E402


def auc(pos: np.ndarray, neg: np.ndarray) -> float:
    u = stats.mannwhitneyu(pos, neg, alternative="two-sided").statistic
    return u / (len(pos) * len(neg))


def cohens_d(a: np.ndarray, b: np.ndarray) -> float:
    pooled = np.sqrt(((len(a) - 1) * a.var(ddof=1) + (len(b) - 1) * b.var(ddof=1)) / (len(a) + len(b) - 2))
    return (a.mean() - b.mean()) / pooled


def rescore(v: pd.DataFrame, b: Baseline, hr_max: float, br_max: float) -> pd.Series:
    old = metrics.HR_MAX_PCT, metrics.BR_MAX_PCT
    metrics.HR_MAX_PCT, metrics.BR_MAX_PCT = hr_max, br_max
    try:
        return v.apply(lambda r: metrics.stress_score(VitalsReading(
            ts=r["time"].to_pydatetime().astimezone(timezone.utc),
            heart_rate=None if pd.isna(r["heart_rate"]) else r["heart_rate"],
            breathing_rate=None if pd.isna(r["breathing_rate"]) else r["breathing_rate"],
            focus=None if pd.isna(r["focus"]) else r["focus"], confidence=r["confidence"]), b), axis=1)
    finally:
        metrics.HR_MAX_PCT, metrics.BR_MAX_PCT = old


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name")
    args = ap.parse_args()
    S = style.SAMPLES
    v = pd.read_csv(S / f"{args.name}_vitals.csv")
    v["time"] = pd.to_datetime(v["time"], utc=True, format="ISO8601")
    ev = pd.read_csv(S / f"{args.name}_events.csv")
    ev["time"] = pd.to_datetime(ev["time"], utc=True, format="ISO8601")
    ev = ev[ev["time"].between(v["time"].min(), v["time"].max())]
    s = pd.read_csv(S / f"{args.name}_session.csv").iloc[0]
    b = Baseline(heart_rate=s["baseline_hr"], breathing_rate=s["baseline_br"], focus=s["baseline_focus"],
                 n_samples=int(s["baseline_n"]))
    v["label"] = label_rows(v, ev)
    good = v[v["confidence"] >= 0.7]
    calm = good.loc[good["label"] == "calm", "stress"].to_numpy()
    spike = good.loc[good["label"] == "spike", "stress"].to_numpy()

    # what Brain's watcher sees: mean stress over the last 10 s, every 3 s
    v_idx = v.set_index("time")
    win = v_idx["stress"].rolling("10s", min_periods=3).mean()
    lab = v_idx["label"]
    w_calm = win[lab == "calm"].dropna()
    w_spike = win[lab == "spike"].dropna()

    lines = [f"# Stress separation: `{args.name}`", "",
             f"Session `{s['id']}` ({len(v)} readings). Calm = no event active; spike = 3 to 16 s after an `s` "
             "press. Generated by `scripts/viz/stress_separation.py`.", "",
             "> **Caveat:** this is mock data, so the spike is *defined* by the constants it tests (+25% HR, +30% BR, "
             "focus 0.5). It proves the pipeline separates the two states end to end and measures the calm noise "
             "floor. It cannot tell us the right constants for real people. Re-run on Sensing's real Presage test "
             "sessions (docs/roles/sensing.md: calm 60 s, jumping jacks, mental math) by exporting them and writing "
             "a `<name>_events.csv` with the start time of each test.", "",
             "## Separation", "",
             "| Measure | Per reading | Per 10 s window (Brain's watcher) |", "|---|---|---|",
             f"| Calm: mean (p95) | {calm.mean():.1f} ({np.percentile(calm, 95):.1f}) | "
             f"{w_calm.mean():.1f} ({np.percentile(w_calm, 95):.1f}) |",
             f"| Spike: mean (p5) | {spike.mean():.1f} ({np.percentile(spike, 5):.1f}) | "
             f"{w_spike.mean():.1f} ({np.percentile(w_spike, 5):.1f}) |",
             f"| Cohen's d (spike vs calm) | {cohens_d(spike, calm):.1f} | {cohens_d(w_spike.to_numpy(), w_calm.to_numpy()):.1f} |",
             f"| ROC AUC (stress ranks spike above calm) | {auc(spike, calm):.3f} | {auc(w_spike.to_numpy(), w_calm.to_numpy()):.3f} |",
             f"| Mann-Whitney p | {stats.mannwhitneyu(spike, calm).pvalue:.1e} | "
             f"{stats.mannwhitneyu(w_spike, w_calm).pvalue:.1e} |", "",
             "## Thresholds everyone uses (< 40 calm, 40 to 70 rising, > 70 high)", "",
             "| | Calm readings | Spike readings | Calm 10 s windows | Spike 10 s windows |", "|---|---|---|---|---|",
             f"| above 40 (rising or high) | {(calm > 40).mean():.0%} | {(spike > 40).mean():.0%} | "
             f"{(w_calm > 40).mean():.0%} | {(w_spike > 40).mean():.0%} |",
             f"| above 70 (high) | {(calm > 70).mean():.0%} | {(spike > 70).mean():.0%} | "
             f"{(w_calm > 70).mean():.0%} | {(w_spike > 70).mean():.0%} |", "",
             "Calm above 40 is a false coach flag; spike below 40 is a missed one.", "",
             "## Sensitivity of the constants", "",
             "Same readings re-scored with different `HR_MAX_PCT` / `BR_MAX_PCT` (focus constant unchanged):", "",
             "| HR_MAX_PCT | BR_MAX_PCT | Calm p95 | Spike mean | Spike peak | Calm > 40 |", "|---|---|---|---|---|---|"]
    for hr_max, br_max in ((15, 30), (20, 40), (25, 40), (30, 40), (25, 50), (35, 50)):
        sc = rescore(good, b, hr_max, br_max)
        c, k = sc[good["label"] == "calm"], sc[good["label"] == "spike"]
        mark = " **(current)**" if (hr_max, br_max) == (metrics.HR_MAX_PCT, metrics.BR_MAX_PCT) else ""
        lines.append(f"| {hr_max}{mark} | {br_max} | {c.quantile(0.95):.1f} | {k.mean():.1f} | {k.max():.1f} | "
                     f"{(c > 40).mean():.0%} |")
    lines += ["", "## Recommendation", "",
              f"- **Keep the PLAN.md constants for now** (HR 25%, BR 40%, focus 0.5). On this data calm stays at "
              f"{calm.mean():.0f} (p95 {np.percentile(calm, 95):.0f}), far under 40, and every spike crosses 70, so "
              "nothing needs fixing before Integration 1.",
              "- **Tune with real Presage data, not mock data.** Presage's HR noise will be larger than the mock's "
              "±2 bpm. If real calm p95 comes out above ~25, raise `HR_MAX_PCT` (30 halves the HR noise contribution "
              "relative to 15); if a real stressor (mental math) stays under 40, lower it toward 20.",
              "- sensing.md's jumping-jacks result is the 'stress 100' reference: set `HR_MAX_PCT` near the HR rise "
              "measured there, then check calm p95 with this script.",
              "- Thresholds (40/70) and the 0 to 100 scale are fixed by PLAN.md; only the constants move."]
    out = style.ROOT / "docs" / "data" / f"stats_{args.name}.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(style.ROOT).as_posix()}")


if __name__ == "__main__":
    main()
